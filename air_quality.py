import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns

# 1. Load Dataset
df = pd.read_csv("airquality.csv", sep=";", low_memory=False)
df = df.loc[:, ~df.columns.str.contains("^Unnamed")]

# 2. Data Cleaning and statastical analysis
for c in df.columns:
    if c not in ["Date", "Time"]:
        df[c] = (
            df[c].astype(str).str.replace(",", ".").astype(float, errors="ignore")
        )

df = df.dropna(how="all")
df = df.replace(-200.0, np.nan)


df["Date"] = pd.to_datetime(df["Date"], format="%d/%m/%Y", errors="coerce")
df["Month"] = df["Date"].dt.month_name()

bins = [-np.inf, 10, 20, 30, np.inf]
labels = ["Cold (<10°C)", "Mild (10-20°C)", "Warm (20-30°C)", "Hot (>30°C)"]
df["Temp_Group"] = pd.cut(df["T"], bins=bins, labels=labels)

print("--- DATA INFO ---")
print(df.info())

print("\n--- SUMMARY / DESCRIPTIVE STATISTICS ---")
desc_stats = df.describe().T[["count", "mean", "std", "min", "max"]]
print(desc_stats)

print("\n" + "="*50)

print("="*50)

# Aggregation function for corelation between colounm
group_mean = df.groupby(["Month", "Temp_Group"])[["CO(GT)", "C6H6(GT)"]].mean().reset_index()
print("\n Mean Pollutant Levels grouped by Month and Temp_Group:")
print(group_mean.head(10))


group_extremes = df.groupby(["Month", "Temp_Group"])[["T", "RH"]].agg(["max", "min"]).reset_index()
print("\n[Groupby 2] Temperature and Humidity Extremes grouped by Month and Temp_Group:")
print(group_extremes.head(10))


group_correlation = df.groupby(["Month", "Temp_Group"]).apply(
    lambda g: g["CO(GT)"].corr(g["C6H6(GT)"])
).reset_index(name="CO_vs_Benzene_Correlation")
print("\n[Groupby 3] Correlation between CO(GT) and C6H6(GT) within Month & Temp Groups:")
print(group_correlation.dropna().head(10))



# VISUALIZATIONS

sns.set_theme(style="whitegrid")


plt.figure(figsize=(9, 7))
numeric_df = df.select_dtypes(include=[np.number])
sns.heatmap(numeric_df.corr(), annot=True, fmt=".2f", cmap="coolwarm", linewidths=0.5)
plt.title("Correlation Matrix Heatmap of Air Quality Parameters")
plt.tight_layout()
plt.savefig("heatmap_correlation.png")
plt.show()


plt.figure(figsize=(10, 5))
sns.barplot(data=group_mean.dropna(), x="Month", y="CO(GT)", hue="Temp_Group", palette="viridis")
plt.title("Average CO(GT) by Month across Temperature Categories")
plt.xlabel("Month")
plt.ylabel("Mean CO (GT)")
plt.xticks(rotation=30)
plt.legend(title="Temperature Group")
plt.tight_layout()
plt.savefig("barplot_two_column_groupby.png")
plt.show()

print(
    "\nData cleaning, statistical summaries, 3 two-column groupby analyses, "
    "and visualizations completed successfully!"
)

